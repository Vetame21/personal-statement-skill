#!/usr/bin/env python3
"""Score humanizer outputs against the benchmark samples. Standard library only, Python 3.9+.

    python3 bench/score.py                 # scores every folder in bench/outputs/, writes bench/RESULTS.md

Put each tool's outputs in bench/outputs/<tool>/<sample name>.txt (only the rewritten text), one folder per
tool or condition, then run this script. Metrics, for each output:

- facts kept      share of the sample's facts (bench/samples/facts.json) still present
- new specifics   numbers and capitalised names in the output that are not in the input (possible inventions;
                  check them by hand, a few are harmless, such as a spelled-out number)
- flags           humanize_check.py total flags (AI-typical words, padding phrases, template structure, ...)
- template        template-structure signals (punchline paragraphs, stock reflection, contrast, closing moral)
- length          word count change against the input

Caveat: "flags" and "template" use this repository's own checker, which the Vetame21 humanizer is told to run,
so those two favour it by design. "facts kept" and "new specifics" do not depend on the checker.
"""

import importlib.util
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "skills" / "humanizer" / "scripts"))
spec = importlib.util.spec_from_file_location("humanize_check", ROOT / "skills" / "humanizer" / "scripts" / "humanize_check.py")
hc = importlib.util.module_from_spec(spec)
spec.loader.exec_module(hc)

NUMBER = re.compile(r"\b\d[\d:.,%]*\b|\b(?:one|two|three|four|five|six|seven|eight|nine|ten|eleven|twelve|"
                    r"twenty|thirty|forty|fifty|hundred|thousand|half|dozen)\b", re.I)
WORD = re.compile(r"[A-Za-z][\w'’-]*")


def names(text: str) -> set:
    """Capitalised words that are not at the start of a sentence and not 'I'."""
    out = set()
    text = re.sub(r"\b(Dr|Mr|Mrs|Ms|Prof|St|Jr|Sr|vs|etc|e\.g|i\.e)\.", r"\1", text)   # "Dr. Lee" is one sentence
    for sent in re.split(r"(?<=[.!?])\s+|\n+", text):
        for i, w in enumerate(WORD.findall(sent)):
            if i > 0 and w[0].isupper() and w not in ("I", "I'm", "I've", "I'd", "I'll"):
                out.add(w.strip("'’"))
    return out


def new_specifics(source: str, output: str):
    src_low = source.lower()
    nums = {m.group(0).lower() for m in NUMBER.finditer(output)} - {m.group(0).lower() for m in NUMBER.finditer(source)}
    nums = {n for n in nums if n not in src_low}
    new_names = {n for n in names(output) if n.lower() not in src_low}
    return sorted(nums) + sorted(new_names)


def facts_kept(output: str, facts: dict):
    low = output.lower()
    missing = [name for name, pats in facts.items() if not any(re.search(p, low) for p in pats)]
    return len(facts) - len(missing), len(facts), missing


def score(tool_dir: Path, samples: dict):
    rows = []
    for name, facts in samples.items():
        out_path = tool_dir / name
        if not out_path.exists():
            continue
        source = (HERE / "samples" / name).read_text(encoding="utf-8")
        output = out_path.read_text(encoding="utf-8")
        r_in, r_out = hc.scan(source, "en"), hc.scan(output, "en")
        kept, total, missing = facts_kept(output, facts)
        rows.append({
            "sample": name, "kept": kept, "total": total, "missing": missing,
            "new": new_specifics(source, output),
            "flags_in": hc.total_flags(r_in), "flags_out": hc.total_flags(r_out),
            "template_in": len(r_in["template"]), "template_out": len(r_out["template"]),
            "words_in": r_in["words"], "words_out": r_out["words"],
        })
    return rows


def main() -> int:
    samples = {k: v for k, v in json.loads((HERE / "samples" / "facts.json").read_text(encoding="utf-8")).items()
               if not k.startswith("_")}
    tools = sorted(p for p in (HERE / "outputs").iterdir() if p.is_dir()) if (HERE / "outputs").exists() else []
    if not tools:
        print("No outputs yet: add bench/outputs/<tool>/<sample>.txt")
        return 1
    lines = ["# Benchmark results", "",
             "Generated by `bench/score.py`. Method, conditions and limits: [bench/README.md](README.md).", "",
             "| Tool | Sample | Facts kept | New specifics (check by hand) | Flags in → out | Template in → out | Words in → out |",
             "|---|---|---|---|---|---|---|"]
    summary = []
    for tool in tools:
        rows = score(tool, samples)
        if not rows:
            continue
        for r in rows:
            change = (r["words_out"] - r["words_in"]) / max(r["words_in"], 1) * 100
            lines.append("| " + tool.name + " | " + r["sample"] + " | " + str(r["kept"]) + "/" + str(r["total"])
                         + (" (missing: " + ", ".join(r["missing"]) + ")" if r["missing"] else "") + " | "
                         + (", ".join(r["new"]) if r["new"] else "none") + " | "
                         + str(r["flags_in"]) + " → " + str(r["flags_out"]) + " | "
                         + str(r["template_in"]) + " → " + str(r["template_out"]) + " | "
                         + str(r["words_in"]) + " → " + str(r["words_out"]) + " (" + format(change, "+.0f") + "%) |")
        kept = sum(r["kept"] for r in rows)
        total = sum(r["total"] for r in rows)
        summary.append("| " + tool.name + " | " + str(len(rows)) + " | " + format(kept / total * 100, ".0f") + "% ("
                       + str(kept) + "/" + str(total) + ") | " + str(sum(len(r["new"]) for r in rows)) + " | "
                       + str(sum(r["flags_out"] for r in rows)) + " | " + str(sum(r["template_out"] for r in rows)) + " |")
    lines += ["", "## Totals", "", "| Tool | Samples | Facts kept | New specifics | Flags left | Template signals left |",
              "|---|---|---|---|---|---|"] + summary + [""]
    (HERE / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
